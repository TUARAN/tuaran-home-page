export function getYearSummaryGroups() {
  const grouped = new Map()
  for (const article of YEAR_SUMMARY_ARTICLES) {
    const year = article.date.slice(0, 4)
    if (!grouped.has(year)) grouped.set(year, [])
    grouped.get(year).push(article)
  }

  return Array.from(grouped.entries()).map(([year, articles]) => ({
    year,
    articles,
  }))
}

export function getYearSummaryStats() {
  return YEAR_SUMMARY_ARTICLES.reduce(
    (acc, article) => ({
      articles: acc.articles + 1,
      views: acc.views + article.views,
      diggs: acc.diggs + article.diggs,
      comments: acc.comments + article.comments,
    }),
    { articles: 0, views: 0, diggs: 0, comments: 0 },
  )
}
