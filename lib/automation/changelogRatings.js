const DIMENSION_IDS = CHANGELOG_RATING_DIMENSIONS.map(({ id }) => id)

function buildRating(row) {
  const scores = Object.fromEntries(DIMENSION_IDS.map((id, index) => [id, row[index]]))
  return { scores, note: row[DIMENSION_IDS.length] }
}

export const CHANGELOG_RATINGS = Object.fromEntries(
  Object.entries(RAW).map(([week, row]) => [week, buildRating(row)]),
)

export function getChangelogRating(week) {
  return CHANGELOG_RATINGS[week] || null
}

// 月、季、年视图用：取周期内已评分周的平均值。某维度全是 null 时保持 null。
export function averageChangelogRatings(weeks) {
  const ratings = [...new Set(weeks)].map(getChangelogRating).filter(Boolean)
  if (!ratings.length) return null
  const scores = Object.fromEntries(
    DIMENSION_IDS.map((id) => {
      const values = ratings.map((rating) => rating.scores[id]).filter((value) => value != null)
      if (!values.length) return [id, null]
      return [id, Math.round((values.reduce((sum, value) => sum + value, 0) / values.length) * 10) / 10]
    }),
  )
  return { scores, weeks: ratings.length }
}
