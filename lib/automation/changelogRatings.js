function buildRating([feature, code, design, structure, market, personal, note]) {
  const scores = { feature, code, design, structure, market, personal }
  const values = Object.values(scores)
  const overall = Math.round((values.reduce((sum, value) => sum + value, 0) / values.length) * 10) / 10
  return { scores, overall, note }
}

export const CHANGELOG_RATINGS = Object.fromEntries(
  Object.entries(RAW).map(([week, row]) => [week, buildRating(row)]),
)

export function getChangelogRating(week) {
  return CHANGELOG_RATINGS[week] || null
}

// 月、季、年视图用：取周期内已评分周的平均值。
export function averageChangelogRatings(weeks) {
  const ratings = [...new Set(weeks)].map(getChangelogRating).filter(Boolean)
  if (!ratings.length) return null
  const scores = Object.fromEntries(
    CHANGELOG_RATING_DIMENSIONS.map(({ id }) => [
      id,
      Math.round((ratings.reduce((sum, rating) => sum + rating.scores[id], 0) / ratings.length) * 10) / 10,
    ]),
  )
  const overall = Math.round((ratings.reduce((sum, rating) => sum + rating.overall, 0) / ratings.length) * 10) / 10
  return { scores, overall, weeks: ratings.length }
}
