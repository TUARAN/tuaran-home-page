const SUMMARY_BY_VIEW = {
  month: MONTH_SUMMARIES,
  quarter: QUARTER_SUMMARIES,
  year: YEAR_SUMMARIES,
}

export function getChangelogPeriodSummary(period, view) {
  const curated = SUMMARY_BY_VIEW[view]?.[period.key]
  if (curated) return curated

  const titles = period.entries.map((entry) => entry.title).filter(Boolean)
  return {
    title: titles[0] || `${period.label}更新归纳`,
    summary: `本周期共整理 ${period.entries.length} 次更新，主要围绕${titles.slice(0, 3).join('、')}推进。`,
    highlights: titles.slice(0, 3),
    signal: '该周期尚未补充人工阶段判断，当前内容由更新标题自动归纳。',
  }
}
