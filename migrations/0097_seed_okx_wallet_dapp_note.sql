## 三个阶段对应什么

### 新币对

刚创建或刚进入早期交易阶段的代币会进入新币对。上线时间短、流动性有限，少量资金就可能显著影响价格。历史数据不足，也让真实需求与短期炒作更难区分。

### 即将迁移

「迁移」通常指代币在发射平台完成特定进度后，准备进入新的流动性池或去中心化交易市场。进度、市值和成交变化可以帮助判断市场热度，具体迁移条件仍以对应发射平台的规则为准。

### 已迁移

完成迁移意味着代币进入后续交易阶段，通常拥有新的流动性池和更完整的交易路径。迁移只是一项流程状态，不代表项目可靠、流动性稳定或价格具备支撑。

## 数据应该怎样使用

