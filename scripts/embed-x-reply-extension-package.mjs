import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const version = String(process.argv[2] || '').trim()
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Usage: node scripts/embed-x-reply-extension-package.mjs VERSION')

const fileName = `x-reply-clipboard-extension-v${version}.zip`
const input = path.join(root, 'output', fileName)
const output = path.join(root, 'lib', 'generated', 'xReplyExtensionPackage.js')
const bytes = await readFile(input)
const base64 = bytes.toString('base64')
const sha256 = createHash('sha256').update(bytes).digest('hex')
const source = `// Generated by scripts/embed-x-reply-extension-package.mjs. Do not edit by hand.\n` +
  `export const X_REPLY_EXTENSION_PACKAGE = Object.freeze({\n` +
  `  objectKey: 'downloads/${fileName}',\n` +
  `  fileName: '${fileName}',\n` +
  `  contentType: 'application/zip',\n` +
  `  size: ${bytes.length},\n` +
  `  sha256: '${sha256}',\n` +
  `  base64: '${base64}',\n` +
  `})\n\n` +
  `export function embeddedResourcePackage(objectKey) {\n` +
  `  if (objectKey !== X_REPLY_EXTENSION_PACKAGE.objectKey) return null\n` +
  `  const binary = atob(X_REPLY_EXTENSION_PACKAGE.base64)\n` +
  `  const bytes = new Uint8Array(binary.length)\n` +
  `  for (let index = 0; index < binary.length; index += 1) bytes[index] = binary.charCodeAt(index)\n` +
  `  return { ...X_REPLY_EXTENSION_PACKAGE, bytes }\n` +
  `}\n`

await mkdir(path.dirname(output), { recursive: true })
await writeFile(output, source)
console.log(`${path.relative(root, output)} ${bytes.length} bytes sha256=${sha256}`)
