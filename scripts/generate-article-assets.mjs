#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const sourcePath = path.join(root, 'app/(site)/articles/articlesData.js')
// Evaluate this repository's trusted data module only; JSON imports remain local.
const source = fs.readFileSync(sourcePath, 'utf8').replace(
  /^import (\w+) from '([^']+\.json)'\s*$/gm,
  (_, name, relative) => `const ${name} = ${fs.readFileSync(path.resolve(path.dirname(sourcePath), relative), 'utf8')};`,
).replace('export const articles =', 'const articles =')
const sourceArticles = vm.runInNewContext(`${source}\nJSON.parse(JSON.stringify(articles))`, {}, { timeout: 5000 })
const archiveSlugs = new Set(JSON.parse(fs.readFileSync(path.join(root, 'data/content-archive.json'), 'utf8')).articleSlugs)
const articles = sourceArticles.filter((article) => archiveSlugs.has(article.slug))
const directory = path.join(root, 'public/data/article-archive')
fs.mkdirSync(directory, { recursive: true })
const slugs = new Set()
const metadata = articles.map((article) => {
  if (!/^[a-z0-9-]+$/.test(article.slug) || slugs.has(article.slug)) throw new Error(`Invalid archive slug: ${article.slug}`)
  slugs.add(article.slug)
  fs.writeFileSync(path.join(directory, `${article.slug}.json`), `${JSON.stringify(article)}\n`)
  const { content, markdown, ...meta } = article
  return meta
})
for (const name of fs.readdirSync(directory)) {
  if (name.endsWith('.json') && !slugs.has(name.slice(0, -5))) fs.unlinkSync(path.join(directory, name))
}
fs.writeFileSync(path.join(root, 'lib/articleMetadata.js'), `// Generated by scripts/generate-article-assets.mjs. Metadata only; no article bodies.\nexport const articles = ${JSON.stringify(metadata, null, 2)}\n`)
console.log(`[article-assets] ${articles.length} archived articles; metadata ${Buffer.byteLength(JSON.stringify(metadata))} bytes`)
