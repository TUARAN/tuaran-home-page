import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const categories = ['companies', 'topics', 'people']
const filenameDateRe = /^(\d{4}-\d{2}-\d{2})-(.+)\.md$/i

const keys = []
const articleRedirects = {}
const entryMeta = {}

function parseFrontmatter(raw) {
  if (!raw.startsWith('---')) return {}
  const end = raw.indexOf('\n---', 3)
  if (end === -1) return {}
  const yaml = raw.slice(3, end).trim()
  const data = {}
  for (const line of yaml.split(/\r?\n/)) {
    const match = /^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(.*)$/.exec(line)
    if (!match) continue
    let value = match[2].trim()
    if (!value) continue
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1)
    }
    data[match[1]] = value
  }
  return data
}

// frontmatter 的 tags 是单行 inline list：tags: [a, b, c]
function parseTagList(value) {
  if (typeof value !== 'string') return []
  const inner = value.trim().replace(/^\[/, '').replace(/\]$/, '')
  if (!inner) return []
  return inner
    .split(',')
    .map((t) => t.trim().replace(/^["']|["']$/g, ''))
    .filter(Boolean)
}

const parseInlineList = parseTagList

for (const category of categories) {
  const dir = path.join(root, 'research', category)
  let files = []
  try {
    files = fs.readdirSync(dir)
  } catch {
    continue
  }

  for (const file of files) {
    const match = filenameDateRe.exec(file)
    if (!match) continue
    const slug = match[2]
    const legacySlug = file.replace(/\.md$/i, '')
    const key = `${category}/${slug}`
    const canonicalPath = `/articles/research/${category}/${slug}`
    keys.push(key)
    articleRedirects[slug] = canonicalPath
    articleRedirects[legacySlug] = canonicalPath

    let data = {}
    try {
      data = parseFrontmatter(fs.readFileSync(path.join(dir, file), 'utf8'))
    } catch {
      data = {}
    }
    const date = data.date || match[1]
    const time = data.time || ''
    const tags = parseTagList(data.tags)
    const hasAssessment = data.assessment === 'true' || data.has_assessment === 'true'
    const encrypted = data.encrypted === 'true' || data.encrypted_source === 'true'
    const reviewReady = data.review_ready === 'true'
    const subjects = parseInlineList(data.subjects)
    entryMeta[key] = {
      category,
      slug,
      date,
      ...(time ? { time } : {}),
      title: data.title || slug,
      summary: data.tldr || data.summary || '',
      ...(tags.length ? { tags } : {}),
      ...(hasAssessment ? { hasAssessment: true } : {}),
      ...(encrypted ? { encrypted: true } : {}),
      ...(reviewReady ? { reviewReady: true } : {}),
      ...(subjects.length ? { subjects } : {}),
      ...(data.content_type ? { contentType: data.content_type } : {}),
      ...(data.topic_type ? { topicType: data.topic_type } : {}),
      ...(data.tech_type ? { techType: data.tech_type } : {}),
      ...(data.company_type ? { companyType: data.company_type } : {}),
    }
  }
}

keys.sort()
const redirectEntries = Object.entries(articleRedirects).sort(([a], [b]) => a.localeCompare(b))
const metaEntries = Object.entries(entryMeta).sort(([a], [b]) => a.localeCompare(b))

const content = `// Generated by scripts/generate-research-catalog.mjs. Do not edit by hand.
export const RESEARCH_ENTRY_KEYS = [
${keys.map((key) => `  '${key}',`).join('\n')}
]

export const RESEARCH_ENTRY_KEY_SET = new Set(RESEARCH_ENTRY_KEYS)

export const RESEARCH_REVIEW_READY_KEYS = [
${metaEntries.filter(([, meta]) => meta.reviewReady).map(([key]) => `  '${key}',`).join('\n')}
]

export const RESEARCH_REVIEW_READY_KEY_SET = new Set(RESEARCH_REVIEW_READY_KEYS)

export const RESEARCH_REVIEW_READY_PATHS = [
${metaEntries.filter(([, meta]) => meta.reviewReady).map(([, meta]) => `  '/articles/research/${meta.category}/${meta.slug}',`).join('\n')}
]

export const RESEARCH_REVIEW_READY_PATH_SET = new Set(RESEARCH_REVIEW_READY_PATHS)

export const RESEARCH_ARTICLE_REDIRECTS = {
${redirectEntries.map(([slug, href]) => `  '${slug}': '${href}',`).join('\n')}
}

export const RESEARCH_ENTRY_META = {
${metaEntries.map(([key, meta]) => `  '${key}': ${JSON.stringify(meta)},`).join('\n')}
}
`

fs.writeFileSync(path.join(root, 'lib', 'research', 'catalog.js'), content)
