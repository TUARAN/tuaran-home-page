#!/usr/bin/env node
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { parseResearchGitEditCounts } from '../lib/contentEditCount.js'

export function writeResearchEditCounts(root = process.cwd()) {
  let output = ''
  try {
    output = execFileSync(
      'git',
      ['log', '--diff-filter=M', '--name-only', '--pretty=format:', '--', 'research/companies', 'research/topics', 'research/people'],
      { encoding: 'utf8', cwd: root },
    )
  } catch {
    output = ''
  }

  const counts = parseResearchGitEditCounts(output)
  const entries = Object.entries(counts)
    .filter(([, count]) => count > 0)
    .sort(([left], [right]) => left.localeCompare(right))
  const content = `// Generated by scripts/generate-research-edit-counts.mjs. Do not edit by hand.
export const RESEARCH_EDIT_COUNTS = {
${entries.map(([key, count]) => `  ${JSON.stringify(key)}: ${count},`).join('\n')}
}
`
  fs.writeFileSync(path.join(root, 'lib', 'research', 'editCounts.js'), content)
  return counts
}

if (fileURLToPath(import.meta.url) === path.resolve(process.argv[1] || '')) {
  const counts = writeResearchEditCounts()
  console.log(`[research-edit-counts] ${Object.keys(counts).length} articles with edits`)
}
