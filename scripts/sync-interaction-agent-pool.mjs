#!/usr/bin/env node
/**
 * 把 lib/interaction/agentPool.js 同步到扩展 interactionAgentPool.js（handles + market）。
 * 改账号池后运行：npm run interaction:sync-agent-pool
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { interactionAgentCatalog } from '../lib/interaction/agentPool.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'tools/x-reply-clipboard-extension/interactionAgentPool.js')

const rows = interactionAgentCatalog().map((entry) => (
  `  { name: ${JSON.stringify(entry.name)}, handle: ${JSON.stringify(entry.handle)}, market: ${JSON.stringify(entry.market)} }`
))

const source = `// GENERATED by scripts/sync-interaction-agent-pool.mjs — do not edit by hand.
(function (root) {
  "use strict";

  const CATALOG = Object.freeze([
${rows.join(',\n')}
  ]);

  const MARKET_ZH = "zh";
  const MARKET_EN = "en";

  function normalizeHandle(handle) {
    return String(handle || "").replace(/^@/u, "").trim().toLowerCase();
  }

  function findAgent(handle) {
    const key = normalizeHandle(handle);
    if (!key) return null;
    return CATALOG.find((entry) => entry.handle.toLowerCase() === key) || null;
  }

  function marketForHandle(handle) {
    return findAgent(handle)?.market || null;
  }

  function resolveMarket(handle) {
    const market = marketForHandle(handle);
    return market === MARKET_EN ? MARKET_EN : MARKET_ZH;
  }

  function isEnglishMarket(handle) {
    return resolveMarket(handle) === MARKET_EN;
  }

  const api = {
    CATALOG,
    MARKET_ZH,
    MARKET_EN,
    normalizeHandle,
    findAgent,
    marketForHandle,
    resolveMarket,
    isEnglishMarket
  };
  if (typeof module === "object" && module.exports) module.exports = api;
  root.XrcInteractionAgentPool = api;
})(typeof globalThis !== "undefined" ? globalThis : this);
`

writeFileSync(target, source)
console.log(`synced ${interactionAgentCatalog().length} agents → ${target}`)