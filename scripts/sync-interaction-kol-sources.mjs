#!/usr/bin/env node
/**
 * lib/interaction/kolSources.js → 扩展 kolMarketSources.js
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  KOL_BUILTIN_POOLS,
  KOL_LEADERBOARD_BOARDS,
  KOL_LEADERBOARD_CACHE_KEY,
  INTERACTION_MARKET_EN,
  INTERACTION_MARKET_ZH,
  normalizeKolMarket,
} from '../lib/interaction/kolSources.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'tools/x-reply-clipboard-extension/kolMarketSources.js')

const serialize = (value) => JSON.stringify(value, null, 2)
  .replace(/"([^"]+)":/g, '$1:')

const source = `// GENERATED by scripts/sync-interaction-kol-sources.mjs — do not edit by hand.
(function (root) {
  "use strict";

  const MARKET_ZH = ${JSON.stringify(INTERACTION_MARKET_ZH)};
  const MARKET_EN = ${JSON.stringify(INTERACTION_MARKET_EN)};

  const KOL_BUILTIN_POOLS = Object.freeze(${serialize(KOL_BUILTIN_POOLS)});
  const KOL_LEADERBOARD_BOARDS = Object.freeze(${serialize(KOL_LEADERBOARD_BOARDS)});
  const KOL_LEADERBOARD_CACHE_KEY = Object.freeze(${serialize(KOL_LEADERBOARD_CACHE_KEY)});

  function normalizeKolMarket(value) {
    return String(value || "").toLowerCase() === MARKET_EN ? MARKET_EN : MARKET_ZH;
  }

  function kolMarketForHandle(handle) {
    return root.XrcInteractionAgentPool?.isEnglishMarket?.(handle) ? MARKET_EN : MARKET_ZH;
  }

  function builtinPools(market) {
    const key = normalizeKolMarket(market);
    return KOL_BUILTIN_POOLS[key] || KOL_BUILTIN_POOLS[MARKET_ZH];
  }

  function boards(market) {
    const key = normalizeKolMarket(market);
    return KOL_LEADERBOARD_BOARDS[key] || [];
  }

  function cacheKey(market) {
    const key = normalizeKolMarket(market);
    return KOL_LEADERBOARD_CACHE_KEY[key] || KOL_LEADERBOARD_CACHE_KEY[MARKET_ZH];
  }

  const api = {
    MARKET_ZH,
    MARKET_EN,
    KOL_BUILTIN_POOLS,
    KOL_LEADERBOARD_BOARDS,
    KOL_LEADERBOARD_CACHE_KEY,
    normalizeKolMarket,
    kolMarketForHandle,
    builtinPools,
    boards,
    cacheKey,
  };
  if (typeof module === "object" && module.exports) module.exports = api;
  root.XrcKolMarketSources = api;
})(typeof globalThis !== "undefined" ? globalThis : this);
`

writeFileSync(target, source)
console.log(`synced kol market sources → ${target}`)